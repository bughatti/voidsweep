local KINDS = { "rare", "chest", "worldboss", "event" }

local function toggle(kind)
    local cfg = VS:Config()
    cfg.show[kind] = not cfg.show[kind]
    VS.Pins:Refresh()
    print(("|cff00c7ffVoidSweep|r: %s pins %s"):format(
        kind, cfg.show[kind] and "|cff33ff33shown|r" or "|cffff5555hidden|r"))
end

SLASH_VOIDSWEEP1 = "/voidsweep"
SLASH_VOIDSWEEP2 = "/vsw"
SlashCmdList.VOIDSWEEP = function(msg)
    msg = (msg or ""):lower():gsub("^%s+", ""):gsub("%s+$", "")
    if msg == "rare" or msg == "chest" or msg == "worldboss" or msg == "lore" then
        toggle(msg)
        return
    end
    if msg == "clear" then
        VS.Learned:Clear()
        VS.Pins:Refresh()
        print("|cff00c7ffVoidSweep|r: cleared all remembered locations.")
        return
    end
    if msg == "completed" then
        local cfg = VS:Config()
        cfg.showCompleted = not cfg.showCompleted
        VS.Pins:Refresh()
        print(("|cff00c7ffVoidSweep|r: completed pins %s"):format(
            cfg.showCompleted and "|cff33ff33shown|r" or "|cffff5555hidden|r"))
        return
    end
    if msg == "sync" then
        local cfg = VS:Config()
        cfg.sync = not cfg.sync
        VS.Pins:Refresh()
        VS.Sync:CountNow()
        print(("|cff00c7ffVoidSweep|r: crowd sync %s"):format(
            cfg.sync and "|cff33ff33on|r" or "|cffff5555off|r"))
        return
    end
    if msg == "minimap" then
        local cfg = VS:Config()
        cfg.showMinimap = not cfg.showMinimap
        print(("|cff00c7ffVoidSweep|r: minimap pins %s"):format(
            cfg.showMinimap and "|cff33ff33on|r" or "|cffff5555off|r"))
        return
    end
    if msg == "spawns" then
        local mapID = C_Map.GetBestMapForUnit("player")
        print("|cff00c7ffVoidSweep|r spawn spots for map " .. tostring(mapID) .. ":")
        for _, line in ipairs(VS.Spawns:Report(mapID)) do print("  " .. line) end
        return
    end
    if msg == "here" then
        VS.Sync:WhoHere()    -- other VoidSweep players in this zone; prints in ~6s
        return
    end
    if msg == "box" then     -- the "players here" box (PresenceBox.lua)
        VoidPresence:SetShown(not VoidPresence:IsShown())
        print(("|cff00c7ffVoidSweep|r: players-here box %s"):format(
            VoidPresence:IsShown() and "|cff33ff33on|r (drag it anywhere)" or "|cffff5555off|r"))
        return
    end
    if msg == "layer" then   -- WoW Forever: which layer you're on (Layer.lua)
        local pair, zone = VS.Layer:Here()
        local info = zone and C_Map.GetMapInfo(zone)
        if not (RegionalUniqueNamesEnabled and RegionalUniqueNamesEnabled()) then
            print("|cff00c7ffVoidSweep|r: layers are a WoW Forever thing; nothing to show here.")
        elseif pair then
            print(("|cff00c7ffVoidSweep|r: you're on layer |cffffd200%s|r in %s."):format(pair, info and info.name or "this zone"))
        else
            print("|cff00c7ffVoidSweep|r: layer not known yet. Point at or target any NPC nearby and try again.")
        end
        return
    end
    if msg == "net" or msg == "synctest" then
        VS.Sync:SelfTest()   -- single-client round-trip test; prints results in ~6s
        return
    end
    -- default: open the map + report live + remembered counts
    local live = VS.Scanner:GetLive()
    print(("|cff00c7ffVoidSweep|r: %d up nearby, %d remembered. |cffaaaaaa/vsw rare, chest, worldboss, lore · /vsw completed · /vsw minimap · /vsw sync · /vsw here · /vsw box · /vsw net · /vsw layer · /vsw clear|r")
        :format(#live, VS.Learned:Count()))
    if not WorldMapFrame:IsShown() then
        ToggleWorldMap()
    end
end

-- VoidSweep — Core
--
-- A map-based content radar: a pin for every rare / world boss / treasure /
-- lore object that is UP right now (C_VignetteInfo, the game's own live-spawn
-- system) plus every spot it has seen before (learned + the starter map in
-- Seed.lua, built from VoidSweep's own captures). Click a pin for a Blizzard
-- waypoint. VoidSync shares rare-up sightings between players.
--
-- Files:
--   Core.lua      this — namespace, SavedVars, events, slash
--   Data.lua      learned-location store + seed merge + proximity-clear
--   Seed.lua      starter map (GENERATED by tools/cmd/voidsweep-seed)
--   Scanner.lua   reads live vignettes -> VS.Scanner.live
--   Poi.lua       zone-wide area POIs (world bosses, events)
--   VoidSync.lua  crowd rare-up channel (VoidSweepNet)
--   Route.lua     own waypoint router (portal routing across continents, clear on arrival)
--   Waypoint.lua  VS.Nav:Goto -> Route:Go
--   Pins.lua      MapCanvas data provider + pin mixin
--   Pins.xml      pin frame template
--   Minimap.lua   minimap pins
--   MapButton.lua world-map filter menu
----------------------------------------------------------------------

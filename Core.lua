-- Debounced pin refresh — QUEST_LOG_UPDATE fires in bursts, so coalesce.
local refreshPending = false
local function debouncedRefresh()
    if refreshPending or not WorldMapFrame:IsShown() then return end
    refreshPending = true
    C_Timer.After(0.4, function()
        refreshPending = false
        VS.Pins:Refresh()
    end)
end

local f = CreateFrame("Frame")
f:RegisterEvent("PLAYER_LOGIN")
f:RegisterEvent("VIGNETTES_UPDATED")
f:RegisterEvent("QUEST_LOG_UPDATE")   -- hidden completion quests flag here
f:RegisterEvent("CRITERIA_UPDATE")    -- rares complete via achievement criteria
f:RegisterEvent("AREA_POIS_UPDATED")  -- world-boss / event POIs appear or end
f:RegisterEvent("PLAYER_REGEN_ENABLED")  -- combat ended: safe to draw pins again
f:SetScript("OnEvent", function(_, event)
    if event == "PLAYER_LOGIN" then
        -- the pre-release debug logger is gone; drop what it left behind
        if VoidSweepDB then VoidSweepDB.taintLog = nil end
        VS.Learned:Migrate()   -- purge stale rows from an older classifier
        VS.Scanner:Rescan()
        VS.Pins:Init()
        VS.Sync:Init()
        VS.Minimap:Init()
        VS.MapButton:Init()
        -- catch previously-looted, completion-less chests as you revisit them
        C_Timer.NewTicker(2.5, function()
            if VS.Scanner:ProximityClear() > 0 then VS.Pins:Refresh() end
        end)
    elseif event == "VIGNETTES_UPDATED" then
        VS.Scanner:Rescan()
        VS.Scanner:ProximityClear()   -- looting removes a vignette → clear it
        VS.Pins:Refresh()
        -- completion (quest/criteria) can flag a couple seconds after a kill;
        -- re-check so the pin drops without waiting for a reload.
        C_Timer.After(2.5, function() VS.Pins:Refresh() end)
    elseif event == "QUEST_LOG_UPDATE" or event == "CRITERIA_UPDATE"
        or event == "AREA_POIS_UPDATED" then
        -- a looted chest flags its quest / a killed rare flags its criteria
        -- a beat after the vignette vanishes; re-check completion to hide it.
        debouncedRefresh()
    elseif event == "PLAYER_REGEN_ENABLED" then
        VS.Pins:Refresh()   -- redraw pins suppressed during combat
    end
end)


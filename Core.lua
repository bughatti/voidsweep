VS.defaults = {
    -- Clean default: core content on, collectibles opt-in (toggle via the map
    -- button). This is the anti-"busy as hell" — the map is focused until you
    -- ask for more.
    show = { rare = true, chest = true, worldboss = true, lore = true },
    showCompleted = false,   -- show treasures you've already looted
    sync = true,             -- crowd rare-up broadcasts (VoidSync)
    showMinimap = true,      -- known/reported pins on the minimap
}

-- A record is "done" when its completion quest (the vignette's reward quest,
-- per character) is flagged — i.e. the treasure is looted. Records without a
-- quest never count as done (proximity-clear in Data.lua covers some).
function VS:IsDone(rec)
    return rec and rec.questID and C_QuestLog.IsQuestFlaggedCompleted(rec.questID) or false
end

function VS:Config()
    VoidSweepDB = VoidSweepDB or {}
    if not VoidSweepDB.config then
        VoidSweepDB.config = CopyTable(VS.defaults)
    end
    -- backfill any new keys added since the user last saved
    for k, v in pairs(VS.defaults.show) do
        if VoidSweepDB.config.show[k] == nil then
            VoidSweepDB.config.show[k] = v
        end
    end
    if VoidSweepDB.config.showCompleted == nil then
        VoidSweepDB.config.showCompleted = VS.defaults.showCompleted
    end
    if VoidSweepDB.config.sync == nil then
        VoidSweepDB.config.sync = VS.defaults.sync
    end
    if VoidSweepDB.config.showMinimap == nil then
        VoidSweepDB.config.showMinimap = VS.defaults.showMinimap
    end
    return VoidSweepDB.config
end

